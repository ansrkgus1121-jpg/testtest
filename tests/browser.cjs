// Run with NODE_PATH pointing to an installed playwright package.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const base=process.env.RIBBON_URL||'http://127.0.0.1:8765';
const app=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
 const page=await browser.newPage({viewport:{width:1200,height:950},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(base);await page.locator('#file').setInputFiles(path.join(app,'samples/carefree-20s.mp3'));
  const started=Date.now();
  const uploadResponse=page.waitForResponse(r=>r.url()===base+'/api/jobs'&&r.request().method()==='POST');
  await page.locator('#analyze').click();
  const submission=await (await uploadResponse).json();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('분석 완료'),{},{timeout:180000});
  const readySeconds=(Date.now()-started)/1000;
  assert.equal(await page.locator('#settings').isDisabled(),false);
  assert.equal(await page.locator('#stems input').count(),4);
  await page.evaluate(()=>document.querySelector('audio').play());
  await page.waitForFunction(()=>document.querySelector('audio').currentTime>1);
  await page.evaluate(()=>document.querySelector('audio').pause());
  const t=await page.locator('audio').evaluate(a=>a.currentTime);
  await page.waitForTimeout(200);
  const paused1=await page.locator('#canvas').screenshot();await page.waitForTimeout(350);
  const paused2=await page.locator('#canvas').screenshot();assert.ok(paused1.equals(paused2),'paused image remains fixed');
  await page.locator('audio').evaluate(a=>a.currentTime=8);
  await page.waitForTimeout(250);
  const sought=await page.locator('#canvas').screenshot();assert.ok(!sought.equals(paused1),'seek changes ribbon shape');
  const source=await page.locator('audio').getAttribute('src');
  const data=await (await page.request.get(base+source.replace('/audio','/features'))).json();
  const expected=data.stems.bass.energy[400];
  assert.ok(Math.abs((await page.locator('#meter-bass').evaluate(e=>e.value))-expected)<.002,'seek uses exact audio time');
  await page.locator('#strength').fill('1.8');await page.locator('#palette').selectOption('bright');
  await page.locator('[data-stem="drums"]').uncheck();await page.waitForTimeout(100);
  assert.ok(!(await page.locator('#canvas').screenshot()).equals(sought),'settings change output');
  await page.locator('[data-stem="drums"]').check();
  await page.locator('#palette').selectOption('default');await page.locator('#strength').fill('1');
  await page.screenshot({path:path.resolve(app,'../test-screenshot.png'),fullPage:true});
  await page.reload();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('분석 완료'));
  await page.locator('#sample').click();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('기존 분석'));
  await page.locator('audio').evaluate(a=>a.play());
  await page.locator('#file').setInputFiles({name:'broken.mp3',mimeType:'audio/mpeg',buffer:Buffer.from('bad audio')});
  await page.locator('#analyze').click();
  assert.equal(await page.locator('audio').evaluate(a=>a.paused),true);
  await page.waitForFunction(()=>document.querySelector('#status').classList.contains('error'),{},{timeout:20000});
  assert.equal(await page.locator('#analyze').isDisabled(),false);
  await page.locator('#remove').click();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('삭제했습니다'));
  await page.locator('#sample').click();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('분석 완료'));
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.setViewportSize({width:1200,height:950});
  const reduced=await browser.newPage({reducedMotion:'reduce'});await reduced.goto(base);
  assert.equal(await reduced.locator('#motion').isChecked(),false);await reduced.close();
  assert.deepEqual(errors,[]);
  const result={passed:true,initialCached:!!submission.cached,readySeconds,checks:['upload','actual Demucs result','playback','pause image stability','seek time alignment','strength/palette/visibility','reload restore','sample/cache','corrupt file and retry','delete','responsive','reduced motion','no JS errors'],playbackTime:t,stemFrames:Object.fromEntries(Object.entries(data.stems).map(([n,s])=>[n,s.energy.length]))};
  fs.writeFileSync(path.resolve(app,'../browser-test-results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
